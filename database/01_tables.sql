/* ---------------------------------------------------------------------
   1. SEQUENCES that generate the IDs (SQL Server 2012+)
      A SEQUENCE is a database object that hands out the next number (NEXT VALUE FOR).
      The DEFAULT of an ID column (e.g. DF_STUDENT_StudentId) turns that number into a readable
      code: 'ST' + RIGHT('00000' + number, 5) = ST00001. So the database, not the application,
      generates the IDs, and a procedure reads the new ID back with OUTPUT (usp_Student_Add).
      The DEFAULT applies when an INSERT leaves the column out; the seed data inserts fixed
      IDs and then moves the sequence on with ALTER SEQUENCE ... RESTART (07_seed_data.sql).
      The padded part has a fixed width (4 to 6 digits), which limits how many IDs a sequence can
      produce: MAXVALUE is that limit (9999 for EM0001), so the next number fails with a clear error
      instead of RIGHT() cutting 10000 down to EM0000, a code that already exists (test T66).
      Tables with codes chosen by the user (BRANCH, ROOM, PROGRAM, COURSE, PROMOTION)
      have no sequence; technical keys use IDENTITY (GRADE_COMPONENT, CLASS_SESSION, PAYROLL,
      AUDIT_LOG).
   --------------------------------------------------------------------- */
CREATE SEQUENCE dbo.seq_EMPLOYEE       AS INT START WITH 1 INCREMENT BY 1 MAXVALUE 9999   NO CYCLE;
CREATE SEQUENCE dbo.seq_TEACHER        AS INT START WITH 1 INCREMENT BY 1 MAXVALUE 9999   NO CYCLE;
CREATE SEQUENCE dbo.seq_STUDENT        AS INT START WITH 1 INCREMENT BY 1 MAXVALUE 99999  NO CYCLE;
CREATE SEQUENCE dbo.seq_CLASS          AS INT START WITH 1 INCREMENT BY 1 MAXVALUE 9999   NO CYCLE;
CREATE SEQUENCE dbo.seq_ENROLLMENT     AS INT START WITH 1 INCREMENT BY 1 MAXVALUE 999999 NO CYCLE;
CREATE SEQUENCE dbo.seq_RECEIPT        AS INT START WITH 1 INCREMENT BY 1 MAXVALUE 999999 NO CYCLE;
CREATE SEQUENCE dbo.seq_PLACEMENT_TEST AS INT START WITH 1 INCREMENT BY 1 MAXVALUE 99999  NO CYCLE;
CREATE SEQUENCE dbo.seq_CERTIFICATE    AS INT START WITH 1 INCREMENT BY 1 MAXVALUE 99999  NO CYCLE;
GO

/* ---------------------------------------------------------------------
   2. XML SCHEMA COLLECTION for course syllabuses (typed XML)
      The XSD below describes a valid syllabus: a Syllabus root with one or more Textbook
      elements (optional Author and Year attributes), one Objective, then one or more Unit
      elements (required No and Sessions attributes) that each hold a Title and one or more Skill.
      COURSE.SyllabusXml is declared XML (CONTENT dbo.xsc_CourseSyllabus), so SQL Server checks
      every value against this schema and rejects one that does not follow it (test T27). Typed
      XML also knows the data types (No, Sessions and Year are xs:int). The syllabus is read with
      XQuery by usp_Course_FindBySkill, usp_Course_Syllabus and 08_demo_queries.sql.
      TEACHER.ProfileXml and the AUDIT_LOG columns are untyped XML (any well-formed XML).
   --------------------------------------------------------------------- */
CREATE XML SCHEMA COLLECTION dbo.xsc_CourseSyllabus AS N'
<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema" elementFormDefault="qualified">
  <xs:element name="Syllabus">
    <xs:complexType>
      <xs:sequence>
        <xs:element name="Textbook" maxOccurs="unbounded">
          <xs:complexType>
            <xs:simpleContent>
              <xs:extension base="xs:string">
                <xs:attribute name="Author" type="xs:string" use="optional"/>
                <xs:attribute name="Year" type="xs:int" use="optional"/>
              </xs:extension>
            </xs:simpleContent>
          </xs:complexType>
        </xs:element>
        <xs:element name="Objective" type="xs:string"/>
        <xs:element name="Unit" maxOccurs="unbounded">
          <xs:complexType>
            <xs:sequence>
              <xs:element name="Title" type="xs:string"/>
              <xs:element name="Skill" type="xs:string" maxOccurs="unbounded"/>
            </xs:sequence>
            <xs:attribute name="No" type="xs:int" use="required"/>
            <xs:attribute name="Sessions" type="xs:int" use="required"/>
          </xs:complexType>
        </xs:element>
      </xs:sequence>
    </xs:complexType>
  </xs:element>
</xs:schema>';
GO

/* ---------------------------------------------------------------------
   3. BRANCH - Branches of the center
      One row = one branch; its code (BR01, BR02 ...) is chosen by the user. ROOM, EMPLOYEE,
      TEACHER, STUDENT and CLASS all reference a branch: this is the basis of the horizontal
      fragmentation by branch in 11_distributed_demo.sql. Only Active branches are offered in the
      combo boxes of the application (SqlCatalogRepository).
      CK_BRANCH_Phone: digits only ([^0-9] matches any character that is not a digit, so NOT LIKE
      '%[^0-9]%' means "no such character") and 9 to 11 digits long. CK_BRANCH_Email: a simple
      pattern "x@y.z" (_ = exactly one character, % = any text). EMPLOYEE, TEACHER and STUDENT
      repeat the same two checks.
   --------------------------------------------------------------------- */
CREATE TABLE dbo.BRANCH (
    BranchId    VARCHAR(10)    NOT NULL,
    BranchName  NVARCHAR(100)  NOT NULL,
    Address     NVARCHAR(200)  NOT NULL,
    Phone       VARCHAR(15)    NULL,
    Email       VARCHAR(100)   NULL,
    FoundedOn   DATE           NULL,
    Status      NVARCHAR(20)   NOT NULL CONSTRAINT DF_BRANCH_Status DEFAULT (N'Active'),
    CONSTRAINT PK_BRANCH PRIMARY KEY (BranchId),
    CONSTRAINT UQ_BRANCH_BranchName UNIQUE (BranchName),
    CONSTRAINT CK_BRANCH_Phone CHECK (Phone NOT LIKE '%[^0-9]%' AND LEN(Phone) BETWEEN 9 AND 11),
    CONSTRAINT CK_BRANCH_Email CHECK (Email LIKE '%_@_%._%'),
    CONSTRAINT CK_BRANCH_Status CHECK (Status IN (N'Active', N'Suspended'))
);
GO

/* ---------------------------------------------------------------------
   4. ROOM - Classrooms of a branch
      One row = one classroom of one branch (FK_ROOM_BRANCH).
      UQ_ROOM_BranchId_RoomName: a room name is unique inside its branch only, so two branches may
      use the same room name. Capacity is the upper limit for CLASS.MaxStudents; that rule (and
      "the room belongs to the branch of the class") needs two tables, so trg_CLASS_CheckRoom in
      05_triggers.sql checks it when a class is created or changed.
   --------------------------------------------------------------------- */
CREATE TABLE dbo.ROOM (
    RoomId    VARCHAR(10)   NOT NULL,
    BranchId  VARCHAR(10)   NOT NULL,
    RoomName  NVARCHAR(50)  NOT NULL,
    Capacity  INT           NOT NULL,
    RoomType  NVARCHAR(30)  NOT NULL CONSTRAINT DF_ROOM_RoomType DEFAULT (N'Lecture'),
    Status    NVARCHAR(20)  NOT NULL CONSTRAINT DF_ROOM_Status DEFAULT (N'Available'),
    CONSTRAINT PK_ROOM PRIMARY KEY (RoomId),
    CONSTRAINT FK_ROOM_BRANCH FOREIGN KEY (BranchId) REFERENCES dbo.BRANCH (BranchId),
    CONSTRAINT UQ_ROOM_BranchId_RoomName UNIQUE (BranchId, RoomName),
    CONSTRAINT CK_ROOM_Capacity CHECK (Capacity BETWEEN 1 AND 100),
    CONSTRAINT CK_ROOM_RoomType CHECK (RoomType IN (N'Lecture', N'Lab', N'Multi-purpose')),
    CONSTRAINT CK_ROOM_Status CHECK (Status IN (N'Available', N'Maintenance'))
);
GO

/* ---------------------------------------------------------------------
   5. EMPLOYEE - Office staff (manager, academic staff, accountant, consultant)
      One row = one staff member working at one branch; EmployeeId (EM0001 ...) comes from
      seq_EMPLOYEE through its DEFAULT. An employee may have one sign-in ACCOUNT (roles MANAGER,
      ACADEMIC_STAFF, ACCOUNTANT) and is recorded as the person who enrolled a student
      (ENROLLMENT.EnrolledByEmployeeId) or collected a payment (RECEIPT.CollectedByEmployeeId).
      Phone is required and UNIQUE; Email is optional, so its uniqueness is a filtered unique index.
   --------------------------------------------------------------------- */
CREATE TABLE dbo.EMPLOYEE (
    EmployeeId   VARCHAR(10)    NOT NULL CONSTRAINT DF_EMPLOYEE_EmployeeId
                     DEFAULT ('EM' + RIGHT('0000' + CAST(NEXT VALUE FOR dbo.seq_EMPLOYEE AS VARCHAR(10)), 4)),
    FullName     NVARCHAR(100)  NOT NULL,
    DateOfBirth  DATE           NOT NULL,
    Gender       NVARCHAR(10)   NOT NULL,
    Phone        VARCHAR(15)    NOT NULL,
    Email        VARCHAR(100)   NULL,
    Address      NVARCHAR(200)  NULL,
    Position     NVARCHAR(30)   NOT NULL,
    BranchId     VARCHAR(10)    NOT NULL,
    HireDate     DATE           NOT NULL CONSTRAINT DF_EMPLOYEE_HireDate
                     DEFAULT (CAST(SWITCHOFFSET(SYSDATETIMEOFFSET(), '+07:00') AS DATE)),
    BaseSalary   DECIMAL(12,0)  NOT NULL CONSTRAINT DF_EMPLOYEE_BaseSalary DEFAULT (0),
    Status       NVARCHAR(20)   NOT NULL CONSTRAINT DF_EMPLOYEE_Status DEFAULT (N'Working'),
    CONSTRAINT PK_EMPLOYEE PRIMARY KEY (EmployeeId),
    CONSTRAINT FK_EMPLOYEE_BRANCH FOREIGN KEY (BranchId) REFERENCES dbo.BRANCH (BranchId),
    CONSTRAINT UQ_EMPLOYEE_Phone UNIQUE (Phone),
    CONSTRAINT CK_EMPLOYEE_Gender CHECK (Gender IN (N'Male', N'Female', N'Other')),
    CONSTRAINT CK_EMPLOYEE_Phone CHECK (Phone NOT LIKE '%[^0-9]%' AND LEN(Phone) BETWEEN 9 AND 11),
    CONSTRAINT CK_EMPLOYEE_Email CHECK (Email LIKE '%_@_%._%'),
    CONSTRAINT CK_EMPLOYEE_Position CHECK (Position IN (N'Manager', N'Academic staff', N'Accountant', N'Consultant')),
    CONSTRAINT CK_EMPLOYEE_BaseSalary CHECK (BaseSalary >= 0),
    -- Cross-column constraint: an employee must be at least 18 years old when hired
    CONSTRAINT CK_EMPLOYEE_Age CHECK (DATEADD(YEAR, 18, DateOfBirth) <= HireDate),
    CONSTRAINT CK_EMPLOYEE_Status CHECK (Status IN (N'Working', N'Left'))
);
GO
-- UNIQUE on a nullable column: a filtered index (several NULL rows remain valid)
-- A UNIQUE constraint in SQL Server treats NULLs as equal and so allows only ONE row without an
-- email. WHERE Email IS NOT NULL limits the index to the rows that have an email: those must be
-- unique, while any number of employees may have no email. The same idea is used for ACCOUNT and STUDENT.
CREATE UNIQUE INDEX UX_EMPLOYEE_Email ON dbo.EMPLOYEE (Email) WHERE Email IS NOT NULL;
GO

/* ---------------------------------------------------------------------
   6. TEACHER - Teachers (Vietnamese / native speakers), XML profile
      One row = one teacher with a home branch. A teacher is the main teacher of classes
      (CLASS.TeacherId), teaches sessions (CLASS_SESSION.TeacherId), is paid per hour
      (HourlyRate, used by usp_Payroll_Finalize) and may have one ACCOUNT with the role TEACHER.
      Email is required here, so a normal UNIQUE constraint is enough (no filtered index).
      ProfileXml is UNTYPED XML (no schema): certificates with scores, experience and specialties,
      read with XQuery by usp_Teacher_FindByCertificate and 08_demo_queries.sql.
      HourlyRate is sensitive: academic staff get a column-level GRANT without it (06_security.sql).
   --------------------------------------------------------------------- */
CREATE TABLE dbo.TEACHER (
    TeacherId    VARCHAR(10)    NOT NULL CONSTRAINT DF_TEACHER_TeacherId
                     DEFAULT ('TE' + RIGHT('0000' + CAST(NEXT VALUE FOR dbo.seq_TEACHER AS VARCHAR(10)), 4)),
    FullName     NVARCHAR(100)  NOT NULL,
    DateOfBirth  DATE           NOT NULL,
    Gender       NVARCHAR(10)   NOT NULL,
    Nationality  NVARCHAR(50)   NOT NULL CONSTRAINT DF_TEACHER_Nationality DEFAULT (N'Vietnam'),
    Phone        VARCHAR(15)    NOT NULL,
    Email        VARCHAR(100)   NOT NULL,
    Degree       NVARCHAR(20)   NOT NULL,
    TeacherType  NVARCHAR(20)   NOT NULL,
    HourlyRate   DECIMAL(12,0)  NOT NULL,
    ProfileXml   XML            NULL,
    BranchId     VARCHAR(10)    NOT NULL,
    HireDate     DATE           NOT NULL CONSTRAINT DF_TEACHER_HireDate
                     DEFAULT (CAST(SWITCHOFFSET(SYSDATETIMEOFFSET(), '+07:00') AS DATE)),
    Status       NVARCHAR(20)   NOT NULL CONSTRAINT DF_TEACHER_Status DEFAULT (N'Teaching'),
    CONSTRAINT PK_TEACHER PRIMARY KEY (TeacherId),
    CONSTRAINT FK_TEACHER_BRANCH FOREIGN KEY (BranchId) REFERENCES dbo.BRANCH (BranchId),
    CONSTRAINT UQ_TEACHER_Phone UNIQUE (Phone),
    CONSTRAINT UQ_TEACHER_Email UNIQUE (Email),
    CONSTRAINT CK_TEACHER_Gender CHECK (Gender IN (N'Male', N'Female', N'Other')),
    CONSTRAINT CK_TEACHER_Phone CHECK (Phone NOT LIKE '%[^0-9]%' AND LEN(Phone) BETWEEN 9 AND 11),
    CONSTRAINT CK_TEACHER_Email CHECK (Email LIKE '%_@_%._%'),
    CONSTRAINT CK_TEACHER_Degree CHECK (Degree IN (N'Bachelor', N'Master', N'PhD')),
    CONSTRAINT CK_TEACHER_TeacherType CHECK (TeacherType IN (N'Vietnamese', N'Native')),
    CONSTRAINT CK_TEACHER_HourlyRate CHECK (HourlyRate > 0),
    -- Cross-column constraint: a native-speaker teacher cannot have Vietnamese nationality
    CONSTRAINT CK_TEACHER_Native CHECK (TeacherType = N'Vietnamese' OR Nationality <> N'Vietnam'),
    -- Cross-column constraint: like an employee, a teacher is at least 18 years old when hired
    CONSTRAINT CK_TEACHER_Age CHECK (DATEADD(YEAR, 18, DateOfBirth) <= HireDate),
    CONSTRAINT CK_TEACHER_Status CHECK (Status IN (N'Teaching', N'On leave', N'Left'))
);
GO

/* ---------------------------------------------------------------------
   7. ACCOUNT - Application sign-in accounts.
      Username equals the name of the (contained) database USER;
      passwords are managed by SQL Server (never stored in a table).
      One row = one sign-in account. usp_Account_Create inserts the row AND creates the USER with
      the same name in one transaction, then adds the user to the database role of Role
      (MANAGER -> rl_Manager ...). The signed-in account is found by comparing Username with
      USER_NAME() (fn_CurrentRole, vw_CurrentAccount). Role holds codes without diacritics or
      spaces, so it is VARCHAR. Status Locked goes with DENY CONNECT on the user (usp_Account_Lock).
      CK_ACCOUNT_Owner + the two filtered unique indexes below: an account belongs to exactly one
      person (a TEACHER for the role TEACHER, an EMPLOYEE for every other role) and a person has
      at most one account.
   --------------------------------------------------------------------- */
CREATE TABLE dbo.ACCOUNT (
    Username        NVARCHAR(50)  NOT NULL,
    Role            VARCHAR(20)   NOT NULL,
    EmployeeId      VARCHAR(10)   NULL,
    TeacherId       VARCHAR(10)   NULL,
    Status          NVARCHAR(20)  NOT NULL CONSTRAINT DF_ACCOUNT_Status DEFAULT (N'Active'),
    CreatedAtUtc    DATETIME      NOT NULL CONSTRAINT DF_ACCOUNT_CreatedAtUtc DEFAULT (GETUTCDATE()),
    LastLoginAtUtc  DATETIME      NULL,
    CONSTRAINT PK_ACCOUNT PRIMARY KEY (Username),
    CONSTRAINT FK_ACCOUNT_EMPLOYEE FOREIGN KEY (EmployeeId) REFERENCES dbo.EMPLOYEE (EmployeeId),
    CONSTRAINT FK_ACCOUNT_TEACHER FOREIGN KEY (TeacherId) REFERENCES dbo.TEACHER (TeacherId),
    CONSTRAINT CK_ACCOUNT_Role CHECK (Role IN ('MANAGER', 'ACADEMIC_STAFF', 'ACCOUNTANT', 'TEACHER')),
    CONSTRAINT CK_ACCOUNT_Status CHECK (Status IN (N'Active', N'Locked')),
    -- A teacher account belongs to a TEACHER, every other role to an EMPLOYEE
    CONSTRAINT CK_ACCOUNT_Owner CHECK (
        (Role = 'TEACHER' AND TeacherId IS NOT NULL AND EmployeeId IS NULL) OR
        (Role <> 'TEACHER' AND EmployeeId IS NOT NULL AND TeacherId IS NULL))
);
GO
-- One account per person: only the filled column is checked (the other one is NULL)
CREATE UNIQUE INDEX UX_ACCOUNT_EmployeeId ON dbo.ACCOUNT (EmployeeId) WHERE EmployeeId IS NOT NULL;
CREATE UNIQUE INDEX UX_ACCOUNT_TeacherId ON dbo.ACCOUNT (TeacherId) WHERE TeacherId IS NOT NULL;
GO

/* ---------------------------------------------------------------------
   8. STUDENT - Students
      One row = one learner registered at one branch (StudentId ST00001 ... from seq_STUDENT).
      A student takes placement tests and enrolls in many classes (ENROLLMENT). Status starts as
      Prospective; usp_Enrollment_Create sets a Prospective, On hold or Completed student to Studying;
      usp_Class_EvaluateResults sets Completed when the student takes no other class any more.
      Business rule 1 of docs/DATABASE.md, written as CHECK constraints:
        - CK_STUDENT_DateOfBirth: born after 1930-01-01 and at least 4 years old on the
          registration day
        - CK_STUDENT_Guardian (cross-column): a student under 18 on the registration day must have
          a guardian name AND a guardian phone
        - CK_STUDENT_Contact: the student's phone or the guardian's phone must be known
        - Phone and Email are optional but unique when present (filtered unique indexes below)
      Test cases T01 (no guardian) and T02 (phone with letters) of 12_tests.sql prove these checks.
   --------------------------------------------------------------------- */
CREATE TABLE dbo.STUDENT (
    StudentId      VARCHAR(10)    NOT NULL CONSTRAINT DF_STUDENT_StudentId
                       DEFAULT ('ST' + RIGHT('00000' + CAST(NEXT VALUE FOR dbo.seq_STUDENT AS VARCHAR(10)), 5)),
    FullName       NVARCHAR(100)  NOT NULL,
    DateOfBirth    DATE           NOT NULL,
    Gender         NVARCHAR(10)   NOT NULL,
    Phone          VARCHAR(15)    NULL,
    Email          VARCHAR(100)   NULL,
    Address        NVARCHAR(200)  NULL,
    Occupation     NVARCHAR(50)   NULL,
    GuardianName   NVARCHAR(100)  NULL,
    GuardianPhone  VARCHAR(15)    NULL,
    BranchId       VARCHAR(10)    NOT NULL,
    RegisteredOn   DATE           NOT NULL CONSTRAINT DF_STUDENT_RegisteredOn
                       DEFAULT (CAST(SWITCHOFFSET(SYSDATETIMEOFFSET(), '+07:00') AS DATE)),
    Status         NVARCHAR(20)   NOT NULL CONSTRAINT DF_STUDENT_Status DEFAULT (N'Prospective'),
    Notes          NVARCHAR(500)  NULL,
    CONSTRAINT PK_STUDENT PRIMARY KEY (StudentId),
    CONSTRAINT FK_STUDENT_BRANCH FOREIGN KEY (BranchId) REFERENCES dbo.BRANCH (BranchId),
    CONSTRAINT CK_STUDENT_Gender CHECK (Gender IN (N'Male', N'Female', N'Other')),
    CONSTRAINT CK_STUDENT_Phone CHECK (Phone NOT LIKE '%[^0-9]%' AND LEN(Phone) BETWEEN 9 AND 11),
    CONSTRAINT CK_STUDENT_GuardianPhone CHECK (GuardianPhone NOT LIKE '%[^0-9]%' AND LEN(GuardianPhone) BETWEEN 9 AND 11),
    CONSTRAINT CK_STUDENT_Email CHECK (Email LIKE '%_@_%._%'),
    -- Born after 1930-01-01 and at least 4 years old on the registration day
    CONSTRAINT CK_STUDENT_DateOfBirth CHECK (DateOfBirth > '19300101' AND DATEADD(YEAR, 4, DateOfBirth) <= RegisteredOn),
    -- Cross-column constraint: a student under 18 must have guardian details
    CONSTRAINT CK_STUDENT_Guardian CHECK (
        DATEADD(YEAR, 18, DateOfBirth) <= RegisteredOn
        OR (GuardianName IS NOT NULL AND GuardianPhone IS NOT NULL)),
    -- Must be reachable: the student's phone or the guardian's phone
    CONSTRAINT CK_STUDENT_Contact CHECK (Phone IS NOT NULL OR GuardianPhone IS NOT NULL),
    CONSTRAINT CK_STUDENT_Status CHECK (Status IN (N'Prospective', N'Studying', N'On hold', N'Dropped out', N'Completed'))
);
GO
CREATE UNIQUE INDEX UX_STUDENT_Phone ON dbo.STUDENT (Phone) WHERE Phone IS NOT NULL;
CREATE UNIQUE INDEX UX_STUDENT_Email ON dbo.STUDENT (Email) WHERE Email IS NOT NULL;
CREATE INDEX IX_STUDENT_FullName ON dbo.STUDENT (FullName);
GO

