/* ---------------------------------------------------------------------
   10. COURSE - Courses (CEFR level), self-reference to the prerequisite
       One row = one course of a program, with its number and length of sessions and its list
       tuition; a course is opened many times as classes (CLASS). Level is a CEFR code from A1
       (beginner) to C2 (mastery). SessionCount tells usp_Class_GenerateSessions how many
       sessions to create for a class.
       Recursive relationship: PrerequisiteCourseId references another COURSE row
       (FK_COURSE_COURSE). CK_COURSE_Prerequisite forbids a course being its own prerequisite
       (only that direct case; a longer cycle is not checked). usp_Enrollment_Create checks the
       entry requirement: the prerequisite course passed OR the latest placement test score at
       least MinPlacementScore.
       SyllabusXml is typed XML (schema collection of section 2); CONTENT (instead of DOCUMENT)
       also accepts a fragment with more than one top-level element.
   --------------------------------------------------------------------- */
CREATE TABLE dbo.COURSE (
    CourseId              VARCHAR(10)    NOT NULL,
    ProgramId             VARCHAR(10)    NOT NULL,
    CourseName            NVARCHAR(100)  NOT NULL,
    Level                 VARCHAR(2)     NOT NULL,
    SessionCount          INT            NOT NULL,
    SessionMinutes        INT            NOT NULL CONSTRAINT DF_COURSE_SessionMinutes DEFAULT (90),
    Tuition               DECIMAL(12,0)  NOT NULL,
    MinPlacementScore     DECIMAL(4,2)   NULL,
    PrerequisiteCourseId  VARCHAR(10)    NULL,
    SyllabusXml           XML (CONTENT dbo.xsc_CourseSyllabus) NULL,
    Status                NVARCHAR(20)   NOT NULL CONSTRAINT DF_COURSE_Status DEFAULT (N'Open'),
    CONSTRAINT PK_COURSE PRIMARY KEY (CourseId),
    CONSTRAINT FK_COURSE_PROGRAM FOREIGN KEY (ProgramId) REFERENCES dbo.PROGRAM (ProgramId),
    CONSTRAINT FK_COURSE_COURSE FOREIGN KEY (PrerequisiteCourseId) REFERENCES dbo.COURSE (CourseId),
    CONSTRAINT UQ_COURSE_CourseName UNIQUE (CourseName),
    CONSTRAINT CK_COURSE_Level CHECK (Level IN ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),
    CONSTRAINT CK_COURSE_SessionCount CHECK (SessionCount BETWEEN 1 AND 200),
    CONSTRAINT CK_COURSE_SessionMinutes CHECK (SessionMinutes BETWEEN 30 AND 240),
    CONSTRAINT CK_COURSE_Tuition CHECK (Tuition >= 0),
    CONSTRAINT CK_COURSE_MinPlacementScore CHECK (MinPlacementScore BETWEEN 0 AND 10),
    CONSTRAINT CK_COURSE_Prerequisite CHECK (PrerequisiteCourseId <> CourseId),
    CONSTRAINT CK_COURSE_Status CHECK (Status IN (N'Open', N'Discontinued'))
);
GO

/* ---------------------------------------------------------------------
   11. GRADE_COMPONENT - Grade components and their weights per course
       One row = one graded part of a course and its weight in percent (e.g. Homework 20,
       Midterm 30, Final exam 50). ComponentId is an IDENTITY (a number generated by SQL Server).
       The weights of a course must add up to 100, but a CHECK only sees one row and SQL Server
       has no deferred constraints: the total is listed by the view vw_CourseInvalidWeights, and
       usp_Class_EvaluateResults refuses a course that appears there. fn_FinalGrade then computes
       SUM(Score x Weight) / 100.
   --------------------------------------------------------------------- */
CREATE TABLE dbo.GRADE_COMPONENT (
    ComponentId    INT IDENTITY(1,1)  NOT NULL,
    CourseId       VARCHAR(10)        NOT NULL,
    ComponentName  NVARCHAR(50)       NOT NULL,
    Weight         DECIMAL(5,2)       NOT NULL,
    CONSTRAINT PK_GRADE_COMPONENT PRIMARY KEY (ComponentId),
    CONSTRAINT FK_GRADE_COMPONENT_COURSE FOREIGN KEY (CourseId) REFERENCES dbo.COURSE (CourseId),
    CONSTRAINT UQ_GRADE_COMPONENT_CourseId_ComponentName UNIQUE (CourseId, ComponentName),
    CONSTRAINT CK_GRADE_COMPONENT_Weight CHECK (Weight > 0 AND Weight <= 100)
);
GO

/* ---------------------------------------------------------------------
   12. CLASS - Classes (one run of a course at a branch)
       One row = one class: a course opened at a branch with a main teacher, a main room, a start
       date and a maximum size. Tuition is the price of this class: usp_Class_Create copies
       COURSE.Tuition when no other price is given. EndDate stays NULL until
       usp_Class_GenerateSessions sets it to the date of the last session; until then the overlap
       checks assume a class lasts SessionCount weeks (fn_ClassPeriod, never too short).
       Status: Enrolling -> In progress -> Finished, or Cancelled.
       Rules that need the ROOM table are checked by trg_CLASS_CheckRoom (05_triggers.sql): the
       room belongs to the branch of the class and MaxStudents <= ROOM.Capacity.
       BranchId could be read from the room (RoomId -> ROOM.BranchId), so the table is not in 3NF on
       purpose: the branch of a class is what revenue, filters and permissions group by, and it must
       not follow a room that is later moved. trg_CLASS_CheckRoom and trg_ROOM_CheckClasses keep it equal
       to the branch of the room while the class is active.
   --------------------------------------------------------------------- */
