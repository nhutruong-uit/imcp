/* ---------------------------------------------------------------------
   16. ENROLLMENT - A student enrolled in a class (n-n STUDENT - CLASS)
       AmountPaid is a derived attribute = SUM(RECEIPT.Amount) of the valid receipts, kept by a
       trigger (trg_RECEIPT_UpdateAmountPaid).
       One row = one student in one class. It turns the many-to-many relationship STUDENT - CLASS
       into two one-to-many relationships and holds what belongs to the pair: tuition, payments,
       attendance (ATTENDANCE), grades (GRADE), final result and certificate.
       UQ_ENROLLMENT_StudentId_ClassId: a student enrolls in a class only once (usp_Enrollment_Create
       checks it first with a clear message, test T03; the constraint is the last guard).
       Money columns:
         - BaseTuition: CLASS.Tuition copied at enrollment time (usp_Enrollment_Create), so a later
           price change of the class does not change what this student owes
         - DiscountAmount: from the promotion (fn_DiscountAmount), never above BaseTuition
         - TuitionDue: computed column BaseTuition - DiscountAmount; PERSISTED stores the value in
           the row and SQL Server recomputes it whenever one of the two columns changes
         - AmountPaid: stored rather than summed on every read, so lists and balances
           (vw_OutstandingTuition, fn_StudentBalance) read it directly, and CK_ENROLLMENT_AmountPaid
           can forbid paying more than TuitionDue (a backup of the check in the trigger, test T06)
       Dates: EnrolledOn is the day of the enrollment (promotions are valid on it); ClassJoinedOn is the day
       the student started in the CURRENT class - EnrolledOn at enrollment, the transfer day after
       usp_Enrollment_TransferClass - so fn_AttendanceRate only counts the sessions of the class since then
       (CK_ENROLLMENT_ClassJoinedOn: never before EnrolledOn).
       FinalGrade and Result stay NULL until usp_Class_EvaluateResults writes them at the end of
       the course, together with Status Completed (CK_ENROLLMENT_Completed: a result exactly for a completed
       enrollment). Free seats: trg_ENROLLMENT_CheckCapacity (it needs the CLASS table).
   --------------------------------------------------------------------- */
CREATE TABLE dbo.ENROLLMENT (
    EnrollmentId          VARCHAR(10)    NOT NULL CONSTRAINT DF_ENROLLMENT_EnrollmentId
                              DEFAULT ('EN' + RIGHT('000000' + CAST(NEXT VALUE FOR dbo.seq_ENROLLMENT AS VARCHAR(10)), 6)),
    StudentId             VARCHAR(10)    NOT NULL,
    ClassId               VARCHAR(10)    NOT NULL,
    EnrolledOn            DATE           NOT NULL CONSTRAINT DF_ENROLLMENT_EnrolledOn
                              DEFAULT (CAST(SWITCHOFFSET(SYSDATETIMEOFFSET(), '+07:00') AS DATE)),
    ClassJoinedOn         DATE           NOT NULL CONSTRAINT DF_ENROLLMENT_ClassJoinedOn
                              DEFAULT (CAST(SWITCHOFFSET(SYSDATETIMEOFFSET(), '+07:00') AS DATE)),
    BaseTuition           DECIMAL(12,0)  NOT NULL,
    PromotionId           VARCHAR(10)    NULL,
    DiscountAmount        DECIMAL(12,0)  NOT NULL CONSTRAINT DF_ENROLLMENT_DiscountAmount DEFAULT (0),
    TuitionDue            AS (BaseTuition - DiscountAmount) PERSISTED,
    AmountPaid            DECIMAL(12,0)  NOT NULL CONSTRAINT DF_ENROLLMENT_AmountPaid DEFAULT (0),
    Status                NVARCHAR(20)   NOT NULL CONSTRAINT DF_ENROLLMENT_Status DEFAULT (N'Studying'),
    FinalGrade            DECIMAL(4,2)   NULL,
    Result                NVARCHAR(20)   NULL,
    EnrolledByEmployeeId  VARCHAR(10)    NULL,
    CONSTRAINT PK_ENROLLMENT PRIMARY KEY (EnrollmentId),
    CONSTRAINT FK_ENROLLMENT_STUDENT FOREIGN KEY (StudentId) REFERENCES dbo.STUDENT (StudentId),
    CONSTRAINT FK_ENROLLMENT_CLASS FOREIGN KEY (ClassId) REFERENCES dbo.CLASS (ClassId),
    CONSTRAINT FK_ENROLLMENT_PROMOTION FOREIGN KEY (PromotionId) REFERENCES dbo.PROMOTION (PromotionId),
    CONSTRAINT FK_ENROLLMENT_EMPLOYEE FOREIGN KEY (EnrolledByEmployeeId) REFERENCES dbo.EMPLOYEE (EmployeeId),
    CONSTRAINT UQ_ENROLLMENT_StudentId_ClassId UNIQUE (StudentId, ClassId),
    CONSTRAINT CK_ENROLLMENT_ClassJoinedOn CHECK (ClassJoinedOn >= EnrolledOn),
    CONSTRAINT CK_ENROLLMENT_BaseTuition CHECK (BaseTuition >= 0),
    CONSTRAINT CK_ENROLLMENT_DiscountAmount CHECK (DiscountAmount >= 0 AND DiscountAmount <= BaseTuition),
    -- Cross-column constraint: the amount paid never exceeds the tuition due
    CONSTRAINT CK_ENROLLMENT_AmountPaid CHECK (AmountPaid >= 0 AND AmountPaid <= BaseTuition - DiscountAmount),
    CONSTRAINT CK_ENROLLMENT_Status CHECK (Status IN (N'Studying', N'On hold', N'Left', N'Completed')),
    CONSTRAINT CK_ENROLLMENT_FinalGrade CHECK (FinalGrade BETWEEN 0 AND 10),
    CONSTRAINT CK_ENROLLMENT_Result CHECK (Result IN (N'Passed', N'Failed')),
    -- Cross-column constraint: the evaluation writes Status, Result and FinalGrade together
    CONSTRAINT CK_ENROLLMENT_Completed CHECK ((Status = N'Completed' AND Result IS NOT NULL)
                                              OR (Status <> N'Completed' AND Result IS NULL AND FinalGrade IS NULL))
);
GO
CREATE INDEX IX_ENROLLMENT_ClassId ON dbo.ENROLLMENT (ClassId) INCLUDE (StudentId, Status);
GO

/* ---------------------------------------------------------------------
